"""Regenerate: python3 package/powervr/user/shaders/gen_roa.py
Verify checked-in header: same command with --check.
Needs glslangValidator and spirv-val on PATH; no binary patching or .spv files are retained.
"""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    lines = ['// SPDX-License-Identifier: MIT',
             '// Generated by shaders/gen_roa.py from roa.vert, roa.frag and roa_writer.frag; do not edit.',
             '#ifndef POWERVRPROBED_ROA_SPV_H', '#define POWERVRPROBED_ROA_SPV_H',
             '#include <stdint.h>', '']
    with tempfile.TemporaryDirectory(prefix='powervr-roa-') as temp:
        for stage in ('vert', 'frag', 'writer.frag'):
            binary = Path(temp) / (stage + '.spv')
            subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.0',
                            '-o', str(binary), str(root / ('roa_writer.frag' if stage == 'writer.frag' else 'roa.' + stage))], check=True)
            subprocess.run(['spirv-val', '--target-env', 'vulkan1.0', str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack('<%dI' % (len(data) // 4), data)
            lines.append('static const uint32_t kRoa%sSpv[] = {' % stage.split('.')[0].title())
            for i in range(0, len(words), 8):
                lines.append('    ' + ', '.join('0x%08xu' % word for word in words[i:i + 8]) + ',')
            lines.extend(['};', ''])
    lines.append('#endif')
    content = '\n'.join(lines) + '\n'
    header = root.parent / 'powervrprobed_roa_spv.h'
    if args.check:
        if not header.is_file() or header.read_text() != content:
            raise SystemExit('roa SPIR-V header differs: regenerate with this script')
        print('roa SPIR-V header matches validated shaders')
    else:
        header.write_text(content)


if __name__ == '__main__':
    main()
