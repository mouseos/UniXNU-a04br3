// The user view of a BO is write-combined (NativePowerVRGpu.cpp clientMemoryForType()): complete the stores before reading
// them back. The host check (build-a04br3-powervr-probe.py --check) compiles for the build machine's architecture.
#if defined(__aarch64__) || defined(__arm64__)
#define PROBE_BARRIER() __asm__ volatile("dsb sy" ::: "memory")
#else
#define PROBE_BARRIER() __sync_synchronize()
#endif

// ---- Output ----
static int gConsole = -1;
static unsigned gPass, gFail;

void probe_pass(void) { ++gPass; }
void probe_fail(void) { ++gFail; }

void probe_line(const char *format, ...)
{
  char text[512];
  int at = snprintf(text, sizeof text, "powervrprobed: ");
  va_list args;
  va_start(args, format);
  int n = vsnprintf(text + at, sizeof text - (size_t)at - 1, format, args);
  va_end(args);
  if (n < 0) n = 0;
  at += n;
  if (at > (int)sizeof text - 2) at = (int)sizeof text - 2;
  text[at++] = '\n';
  const int fd = gConsole >= 0 ? gConsole : STDERR_FILENO;
  ssize_t done = 0;
  while (done < at) {
    const ssize_t w = write(fd, text + done, (size_t)(at - done));
    if (w <= 0) {
      if (w < 0 && errno == EINTR) continue;
      break;
    }
    done += w;
  }
}

// ---- IOKit ----
#define IO_ERR(x) ((int)(0xe0000000u | (x)))
enum {
  kIOReturnSuccess = 0,
  kIOReturnError = IO_ERR(0x2bc),
  kIOReturnNoMemory = IO_ERR(0x2bd),
  kIOReturnNoResources = IO_ERR(0x2be),
  kIOReturnNoDevice = IO_ERR(0x2c0),
  kIOReturnBadArgument = IO_ERR(0x2c2),
  kIOReturnUnsupported = IO_ERR(0x2c7),
  kIOReturnVMError = IO_ERR(0x2c8),
  kIOReturnIOError = IO_ERR(0x2ca),
  kIOReturnBusy = IO_ERR(0x2d5),
  kIOReturnTimeout = IO_ERR(0x2d6),
  kIOReturnNotReady = IO_ERR(0x2d8),
  kIOReturnNoSpace = IO_ERR(0x2db),
  kIOReturnNotPermitted = IO_ERR(0x2e2),
  kIOReturnOverrun = IO_ERR(0x2e8),
  kIOReturnNotFound = IO_ERR(0x2f0),
};
#define kIOMapAnywhere 0x00000001u

static struct {
  void *(*matching)(const char *name);
  unsigned (*getService)(unsigned mainPort, void *matching);
  int (*open)(unsigned service, unsigned owningTask, uint32_t type, unsigned *connect);
  int (*close)(unsigned connect);
  int (*release)(unsigned object);
  int (*call)(unsigned connect, uint32_t selector, const void *input, size_t inputSize, void *output, size_t *outputSize);
  int (*map)(unsigned connect, uint32_t memoryType, unsigned intoTask, uint64_t *address, uint64_t *size, uint32_t options);
  int (*unmap)(unsigned connect, uint32_t memoryType, unsigned fromTask, uint64_t address);
} io;
static unsigned gConn;

// The kern_return a NativePowerVRUserClient method returns and the Linux errno it stands for (ioReturnOf() in
// NativePowerVRGpu.cpp; WaitFence maps -EIO and every other job failure to kIOReturnIOError).
static const char *krName(int kr)
{
  static char other[24];
  switch (kr) {
  case kIOReturnSuccess: return "ok";
  case kIOReturnError: return "kIOReturnError";
  case kIOReturnNoMemory: return "kIOReturnNoMemory/ENOMEM";
  case kIOReturnNoResources: return "kIOReturnNoResources";
  case kIOReturnNoDevice: return "kIOReturnNoDevice/ENODEV";
  case kIOReturnBadArgument: return "kIOReturnBadArgument/EINVAL";
  case kIOReturnUnsupported: return "kIOReturnUnsupported/ENOTTY";
  case kIOReturnVMError: return "kIOReturnVMError/EFAULT";
  case kIOReturnIOError: return "kIOReturnIOError/EIO";
  case kIOReturnBusy: return "kIOReturnBusy/EBUSY";
  case kIOReturnTimeout: return "kIOReturnTimeout/ETIMEDOUT";
  case kIOReturnNotReady: return "kIOReturnNotReady";
  case kIOReturnNoSpace: return "kIOReturnNoSpace/ENOSPC";
  case kIOReturnNotPermitted: return "kIOReturnNotPermitted/EPERM";
  case kIOReturnOverrun: return "kIOReturnOverrun/E2BIG";
  case kIOReturnNotFound: return "kIOReturnNotFound/ENOENT";
  default: snprintf(other, sizeof other, "0x%08x", (unsigned)kr); return other;
  }
}

// One step: "<name>: <status> (expected <status>)" and the pass/fail count. Returns 1 when the status is the expected one.
static int expect(const char *name, int kr, int expected, const char *detail)
{
  const int ok = kr == expected;
  if (ok) probe_pass(); else probe_fail();
  if (expected == kIOReturnSuccess)
    probe_line("%s %s: %s%s%s", ok ? "PASS" : "FAIL", name, krName(kr), detail && *detail ? "; " : "", detail ? detail : "");
  else
    probe_line("%s %s: %s (expected %s)%s%s", ok ? "PASS" : "FAIL", name, krName(kr), krName(expected),
               detail && *detail ? "; " : "", detail ? detail : "");
  return ok;
}

// Input-only method: output size 0 (NativePowerVRABI.h, DRM_IOW).
static int callIn(uint32_t method, const void *input, size_t size)
{
  return io.call(gConn, method, input, size, NULL, NULL);
}

// In/out method: input and output are the same struct, both exactly sizeof (DRM_IOWR). The record is updated only on
// success, as the Linux ioctl copies it back only then.
static int callInOut(uint32_t method, void *record, size_t size)
{
  unsigned char reply[256];
  size_t replySize = size;
  if (size > sizeof reply) return kIOReturnBadArgument;
  const int kr = io.call(gConn, method, record, size, reply, &replySize);
  if (kr == kIOReturnSuccess) {
    if (replySize != size) return kIOReturnOverrun;
    memcpy(record, reply, size);
  }
  return kr;
}

static int loadIOKit(void)
{
  void *iokit = dlopen("/System/Library/Frameworks/IOKit.framework/IOKit", RTLD_NOW | RTLD_LOCAL);
  if (!iokit) return -1;
  *(void **)&io.matching = dlsym(iokit, "IOServiceMatching");
  *(void **)&io.getService = dlsym(iokit, "IOServiceGetMatchingService");
  *(void **)&io.open = dlsym(iokit, "IOServiceOpen");
  *(void **)&io.close = dlsym(iokit, "IOServiceClose");
  *(void **)&io.release = dlsym(iokit, "IOObjectRelease");
  *(void **)&io.call = dlsym(iokit, "IOConnectCallStructMethod");
  *(void **)&io.map = dlsym(iokit, "IOConnectMapMemory64");
  *(void **)&io.unmap = dlsym(iokit, "IOConnectUnmapMemory64");
  return io.matching && io.getService && io.open && io.close && io.release && io.call && io.map && io.unmap ? 0 : -2;
}

// ---- 2. DevQuery ----
// drm_pvr_ioctl_dev_query_args with a NULL pointer returns the record size; returns that size or 0.
static uint32_t querySize(uint32_t type, const char *name)
{
  struct drm_pvr_ioctl_dev_query_args args = {.type = type, .size = 0, .pointer = 0};
  const int kr = callInOut(NativePowerVRMethodDevQuery, &args, sizeof args);
  char detail[64];
  snprintf(detail, sizeof detail, "size %u", args.size);
  char step[64];
  snprintf(step, sizeof step, "DevQuery %s size", name);
  return expect(step, kr, kIOReturnSuccess, detail) ? args.size : 0;
}

static int query(uint32_t type, void *record, uint32_t size)
{
  struct drm_pvr_ioctl_dev_query_args args = {.type = type, .size = size, .pointer = (uint64_t)(uintptr_t)record};
  return callInOut(NativePowerVRMethodDevQuery, &args, sizeof args);
}

static struct drm_pvr_heap gHeaps[DRM_PVR_HEAP_COUNT];
static uint32_t gHeapCount;

static void devQueries(void)
{
  char detail[256];
  int kr;

  if (querySize(DRM_PVR_DEV_QUERY_GPU_INFO_GET, "GPU_INFO")) {
    struct drm_pvr_dev_query_gpu_info info = {0};
    kr = query(DRM_PVR_DEV_QUERY_GPU_INFO_GET, &info, sizeof info);
    snprintf(detail, sizeof detail, "gpu_id 0x%016llx = BVNC %llu.%llu.%llu.%llu, num_phantoms %u", (unsigned long long)info.gpu_id,
             (unsigned long long)(info.gpu_id >> 48 & 0xffff), (unsigned long long)(info.gpu_id >> 32 & 0xffff),
             (unsigned long long)(info.gpu_id >> 16 & 0xffff), (unsigned long long)(info.gpu_id & 0xffff), info.num_phantoms);
    expect("DevQuery GPU_INFO", kr, kIOReturnSuccess, detail);
  }

  if (querySize(DRM_PVR_DEV_QUERY_RUNTIME_INFO_GET, "RUNTIME_INFO")) {
    struct drm_pvr_dev_query_runtime_info info = {0};
    kr = query(DRM_PVR_DEV_QUERY_RUNTIME_INFO_GET, &info, sizeof info);
    snprintf(detail, sizeof detail,
             "free_list_min_pages %llu, free_list_max_pages %llu, common_store_alloc_region_size %u, "
             "common_store_partition_space_size %u, max_coeffs %u, cdm_max_local_mem_size_regs %u",
             (unsigned long long)info.free_list_min_pages, (unsigned long long)info.free_list_max_pages,
             info.common_store_alloc_region_size, info.common_store_partition_space_size, info.max_coeffs,
             info.cdm_max_local_mem_size_regs);
    expect("DevQuery RUNTIME_INFO", kr, kIOReturnSuccess, detail);
  }

  if (querySize(DRM_PVR_DEV_QUERY_QUIRKS_GET, "QUIRKS")) {
    struct drm_pvr_dev_query_quirks quirks = {0};
    kr = query(DRM_PVR_DEV_QUERY_QUIRKS_GET, &quirks, sizeof quirks);
    snprintf(detail, sizeof detail, "count %u", quirks.count);
    if (expect("DevQuery QUIRKS count", kr, kIOReturnSuccess, detail) && quirks.count) {
      uint32_t list[64] = {0};
      const uint16_t count = quirks.count < 64 ? quirks.count : 64;
      quirks = (struct drm_pvr_dev_query_quirks){.quirks = (uint64_t)(uintptr_t)list, .count = count};
      kr = query(DRM_PVR_DEV_QUERY_QUIRKS_GET, &quirks, sizeof quirks);
      int at = snprintf(detail, sizeof detail, "musthave_count %u:", quirks.musthave_count);
      for (uint16_t i = 0; i < quirks.count && i < count && at < (int)sizeof detail - 12; i++)
        at += snprintf(detail + at, sizeof detail - (size_t)at, " %u", list[i]);
      expect("DevQuery QUIRKS", kr, kIOReturnSuccess, detail);
    }
  }

  if (querySize(DRM_PVR_DEV_QUERY_ENHANCEMENTS_GET, "ENHANCEMENTS")) {
    struct drm_pvr_dev_query_enhancements enhancements = {0};
    kr = query(DRM_PVR_DEV_QUERY_ENHANCEMENTS_GET, &enhancements, sizeof enhancements);
    snprintf(detail, sizeof detail, "count %u", enhancements.count);
    if (expect("DevQuery ENHANCEMENTS count", kr, kIOReturnSuccess, detail) && enhancements.count) {
      uint32_t list[64] = {0};
      const uint16_t count = enhancements.count < 64 ? enhancements.count : 64;
      enhancements = (struct drm_pvr_dev_query_enhancements){.enhancements = (uint64_t)(uintptr_t)list, .count = count};
      kr = query(DRM_PVR_DEV_QUERY_ENHANCEMENTS_GET, &enhancements, sizeof enhancements);
      int at = snprintf(detail, sizeof detail, "list:");
      for (uint16_t i = 0; i < enhancements.count && i < count && at < (int)sizeof detail - 12; i++)
        at += snprintf(detail + at, sizeof detail - (size_t)at, " %u", list[i]);
      expect("DevQuery ENHANCEMENTS", kr, kIOReturnSuccess, detail);
    }
  }

  if (querySize(DRM_PVR_DEV_QUERY_HEAP_INFO_GET, "HEAP_INFO")) {
    struct drm_pvr_dev_query_heap_info heaps = {0};
    kr = query(DRM_PVR_DEV_QUERY_HEAP_INFO_GET, &heaps, sizeof heaps);
    snprintf(detail, sizeof detail, "count %u stride %u", heaps.heaps.count, heaps.heaps.stride);
    if (expect("DevQuery HEAP_INFO count", kr, kIOReturnSuccess, detail)) {
      const uint32_t count = heaps.heaps.count < DRM_PVR_HEAP_COUNT ? heaps.heaps.count : DRM_PVR_HEAP_COUNT;
      heaps.heaps = (struct drm_pvr_obj_array)DRM_PVR_OBJ_ARRAY(count, gHeaps);
      kr = query(DRM_PVR_DEV_QUERY_HEAP_INFO_GET, &heaps, sizeof heaps);
      if (expect("DevQuery HEAP_INFO", kr, kIOReturnSuccess, NULL)) {
        gHeapCount = heaps.heaps.count < count ? heaps.heaps.count : count;
        for (uint32_t i = 0; i < gHeapCount; i++)
          probe_line("heap %u: base 0x%llx size 0x%llx flags %u page_size_log2 %u", i, (unsigned long long)gHeaps[i].base,
                     (unsigned long long)gHeaps[i].size, gHeaps[i].flags, gHeaps[i].page_size_log2);
      }
    }
  }

  if (querySize(DRM_PVR_DEV_QUERY_STATIC_DATA_AREAS_GET, "STATIC_DATA_AREAS")) {
    struct drm_pvr_dev_query_static_data_areas areas = {0};
    kr = query(DRM_PVR_DEV_QUERY_STATIC_DATA_AREAS_GET, &areas, sizeof areas);
    snprintf(detail, sizeof detail, "count %u stride %u", areas.static_data_areas.count, areas.static_data_areas.stride);
    if (expect("DevQuery STATIC_DATA_AREAS count", kr, kIOReturnSuccess, detail)) {
      struct drm_pvr_static_data_area list[16];
      memset(list, 0, sizeof list);
      const uint32_t count = areas.static_data_areas.count < 16 ? areas.static_data_areas.count : 16;
      areas.static_data_areas = (struct drm_pvr_obj_array)DRM_PVR_OBJ_ARRAY(count, list);
      kr = query(DRM_PVR_DEV_QUERY_STATIC_DATA_AREAS_GET, &areas, sizeof areas);
      if (expect("DevQuery STATIC_DATA_AREAS", kr, kIOReturnSuccess, NULL))
        for (uint32_t i = 0; i < areas.static_data_areas.count && i < count; i++)
          probe_line("static data area %u: usage %u heap %u size %u offset 0x%llx", i, list[i].area_usage,
                     list[i].location_heap_id, list[i].size, (unsigned long long)list[i].offset);
    }
  }

  // Not a query type: pvr_ioctl_dev_query() answers -EINVAL.
  struct drm_pvr_ioctl_dev_query_args bad = {.type = DRM_PVR_DEV_QUERY_STATIC_DATA_AREAS_GET + 1, .size = 0, .pointer = 0};
  expect("DevQuery unknown type", callInOut(NativePowerVRMethodDevQuery, &bad, sizeof bad), kIOReturnBadArgument, NULL);
}

// ---- 3. Buffer objects ----
enum { kBoSize = 4 * 4096 };

static int createBo(uint64_t size, uint64_t flags, uint32_t *handle)
{
  struct drm_pvr_ioctl_create_bo_args args = {.size = size, .flags = flags};
  const int kr = callInOut(NativePowerVRMethodCreateBo, &args, sizeof args);
  *handle = kr == kIOReturnSuccess ? args.handle : 0;
  return kr;
}

static int closeBo(uint32_t handle)
{
  struct drm_gem_close args = {.handle = handle};
  return callIn(NativePowerVRMethodGemClose, &args, sizeof args);
}

static uint32_t pattern(uint32_t i) { return 0x50565200u ^ (i * 0x9e3779b1u); }

// Maps the BO through its mmap "offset" (the memory type of clientMemoryForType()) and returns the address, or 0.
static uint64_t mapBo(uint32_t type, uint64_t *size, int *kr)
{
  uint64_t address = 0;
  *size = 0;
  *kr = io.map(gConn, type, mach_task_self(), &address, size, kIOMapAnywhere);
  return *kr == kIOReturnSuccess ? address : 0;
}

static uint32_t bufferObjects(void)
{
  char detail[160];
  uint32_t bo = 0;
  int kr = createBo(kBoSize, DRM_PVR_BO_ALLOW_CPU_USERSPACE_ACCESS, &bo);
  snprintf(detail, sizeof detail, "size %u handle %u", kBoSize, bo);
  if (!expect("CreateBo cpu-access", kr, kIOReturnSuccess, detail)) return 0;

  struct drm_pvr_ioctl_get_bo_mmap_offset_args offset = {.handle = bo};
  kr = callInOut(NativePowerVRMethodGetBoMmapOffset, &offset, sizeof offset);
  snprintf(detail, sizeof detail, "offset 0x%llx", (unsigned long long)offset.offset);
  if (!expect("GetBoMmapOffset", kr, kIOReturnSuccess, detail) || offset.offset >> 32) {
    if (offset.offset >> 32) { probe_fail(); probe_line("FAIL GetBoMmapOffset: offset does not fit the 32-bit memory type"); }
    return bo;
  }
  const uint32_t type = (uint32_t)offset.offset;

  uint64_t size = 0;
  uint64_t address = mapBo(type, &size, &kr);
  snprintf(detail, sizeof detail, "address 0x%llx size 0x%llx", (unsigned long long)address, (unsigned long long)size);
  if (!expect("IOConnectMapMemory64", kr, kIOReturnSuccess, detail)) return bo;
  if (size < kBoSize) {
    probe_fail();
    probe_line("FAIL mapping smaller than the BO: 0x%llx < 0x%x", (unsigned long long)size, kBoSize);
    io.unmap(gConn, type, mach_task_self(), address);
    return bo;
  }
  volatile uint32_t *words = (volatile uint32_t *)(uintptr_t)address;
  unsigned zero = 0;
  for (uint32_t i = 0; i < kBoSize / 4; i++) zero += words[i] == 0;   // pvr_gem_object_zero(): a new BO reads as zero
  for (uint32_t i = 0; i < kBoSize / 4; i++) words[i] = pattern(i);
  PROBE_BARRIER();
  unsigned same = 0;
  for (uint32_t i = 0; i < kBoSize / 4; i++) same += words[i] == pattern(i);
  snprintf(detail, sizeof detail, "%u/%u words zero before, %u/%u read back", zero, kBoSize / 4, same, kBoSize / 4);
  if (zero == kBoSize / 4 && same == kBoSize / 4) { probe_pass(); probe_line("PASS BO write/read: %s", detail); }
  else { probe_fail(); probe_line("FAIL BO write/read: %s", detail); }

  expect("IOConnectUnmapMemory64", io.unmap(gConn, type, mach_task_self(), address), kIOReturnSuccess, NULL);
  address = mapBo(type, &size, &kr);
  if (expect("IOConnectMapMemory64 again", kr, kIOReturnSuccess, NULL)) {
    words = (volatile uint32_t *)(uintptr_t)address;
    same = 0;
    for (uint32_t i = 0; i < kBoSize / 4; i++) same += words[i] == pattern(i);
    snprintf(detail, sizeof detail, "%u/%u words of the first mapping", same, kBoSize / 4);
    if (same == kBoSize / 4) { probe_pass(); probe_line("PASS BO pages kept across mappings: %s", detail); }
    else { probe_fail(); probe_line("FAIL BO pages kept across mappings: %s", detail); }
    io.unmap(gConn, type, mach_task_self(), address);
  }

  // A BO without DRM_PVR_BO_ALLOW_CPU_USERSPACE_ACCESS has an mmap offset but no user mapping (pvr_gem_mmap(): -EINVAL;
  // clientMemoryForType(): kIOReturnBadArgument).
  uint32_t hidden = 0;
  if (expect("CreateBo device-only", createBo(4096, 0, &hidden), kIOReturnSuccess, NULL)) {
    struct drm_pvr_ioctl_get_bo_mmap_offset_args hiddenOffset = {.handle = hidden};
    if (expect("GetBoMmapOffset device-only", callInOut(NativePowerVRMethodGetBoMmapOffset, &hiddenOffset, sizeof hiddenOffset),
               kIOReturnSuccess, NULL)) {
      address = mapBo((uint32_t)hiddenOffset.offset, &size, &kr);
      expect("IOConnectMapMemory64 device-only", kr, kIOReturnBadArgument, NULL);
      if (kr == kIOReturnSuccess) io.unmap(gConn, (uint32_t)hiddenOffset.offset, mach_task_self(), address);
    }
    expect("GemClose device-only", closeBo(hidden), kIOReturnSuccess, NULL);
  }
  return bo;
}

// ---- 4. VM context ----
static uint32_t vmContext(uint32_t bo)
{
  char detail[160];
  struct drm_pvr_ioctl_create_vm_context_args vm = {0};
  int kr = callInOut(NativePowerVRMethodCreateVmContext, &vm, sizeof vm);
  snprintf(detail, sizeof detail, "handle %u", vm.handle);
  if (!expect("CreateVmContext", kr, kIOReturnSuccess, detail)) return 0;
  if (!bo) return vm.handle;
  if (gHeapCount <= DRM_PVR_HEAP_GENERAL || gHeaps[DRM_PVR_HEAP_GENERAL].size < 0x200000) {
    probe_fail();
    probe_line("FAIL VmMap: no general heap from HEAP_INFO");
    return vm.handle;
  }
  // 1 MiB into the general heap, clear of the static data areas at its start (FENCE, YUV_CSC: pvr_vm.c).
  const uint64_t deviceAddr = gHeaps[DRM_PVR_HEAP_GENERAL].base + 0x100000;
  struct drm_pvr_ioctl_vm_map_args map = {.vm_context_handle = vm.handle, .flags = 0, .device_addr = deviceAddr,
                                          .handle = bo, .offset = 0, .size = kBoSize};
  kr = callIn(NativePowerVRMethodVmMap, &map, sizeof map);
  snprintf(detail, sizeof detail, "device 0x%llx size 0x%x", (unsigned long long)deviceAddr, kBoSize);
  if (expect("VmMap", kr, kIOReturnSuccess, detail)) {
    struct drm_pvr_ioctl_vm_unmap_args unmap = {.vm_context_handle = vm.handle, .device_addr = deviceAddr, .size = kBoSize};
    expect("VmUnmap", callIn(NativePowerVRMethodVmUnmap, &unmap, sizeof unmap), kIOReturnSuccess, NULL);
    expect("VmUnmap again", callIn(NativePowerVRMethodVmUnmap, &unmap, sizeof unmap), kIOReturnNotFound, NULL);
  }
  return vm.handle;
}

// ---- 5. Contexts ----
static uint32_t createContext(uint32_t vm, uint32_t type, const void *state, uint32_t stateLen, const char *name)
{
  struct drm_pvr_ioctl_create_context_args args = {.type = type, .flags = 0, .priority = DRM_PVR_CTX_PRIORITY_NORMAL,
                                                   .static_context_state = (uint64_t)(uintptr_t)state,
                                                   .static_context_state_len = stateLen, .vm_context_handle = vm,
                                                   .callstack_addr = 0};
  const int kr = callInOut(NativePowerVRMethodCreateContext, &args, sizeof args);
  char detail[64];
  snprintf(detail, sizeof detail, "handle %u, static state %u bytes", kr == kIOReturnSuccess ? args.handle : 0, stateLen);
  return expect(name, kr, kIOReturnSuccess, detail) ? args.handle : 0;
}

static void destroyContext(uint32_t handle, const char *name)
{
  struct drm_pvr_ioctl_destroy_context_args args = {.handle = handle};
  expect(name, callIn(NativePowerVRMethodDestroyContext, &args, sizeof args), kIOReturnSuccess, NULL);
}

// ---- 6. Submission without GPU work ----
static void submitWithoutWork(uint32_t transferCtx)
{
  // Header of every job stream (pvr_stream_process()): u32 main stream length, u32 padding that must be zero. The padding is
  // 1 here, so the kernel refuses the stream before the job is queued.
  const uint32_t stream[2] = {sizeof stream, 1};
  struct drm_pvr_job job = {.type = DRM_PVR_JOB_TYPE_TRANSFER_FRAG, .context_handle = transferCtx, .flags = 0,
                            .cmd_stream_len = sizeof stream, .cmd_stream = (uint64_t)(uintptr_t)stream,
                            .sync_ops = {.stride = sizeof(struct drm_pvr_sync_op), .count = 0, .array = 0},
                            .hwrt = {.set_handle = 0, .data_index = 0}};
  struct drm_pvr_ioctl_submit_jobs_args submit = {.jobs = DRM_PVR_OBJ_ARRAY(1, &job)};
  struct NativePowerVRAbiSubmitReply reply;
  memset(&reply, 0, sizeof reply);
  size_t replySize = sizeof reply;
  const int kr = io.call(gConn, NativePowerVRMethodSubmitJobs, &submit, sizeof submit, &reply, &replySize);
  char detail[64];
  snprintf(detail, sizeof detail, "fence[0] %llu", (unsigned long long)reply.fence[0]);
  expect("SubmitJobs malformed transfer stream", kr, kIOReturnBadArgument, detail);

  // A fence this connection never issued (NativePowerVRABI.h: kIOReturnBadArgument).
  struct NativePowerVRAbiWaitFence wait = {.fence = 1, .timeout_ns = 0};
  expect("WaitFence never issued", callIn(NativePowerVRMethodWaitFence, &wait, sizeof wait), kIOReturnBadArgument, NULL);
}

// ---- 1 and 7 ----
static int ioStage(unsigned waitSeconds)
{
  if (loadIOKit()) {
    probe_fail();
    probe_line("FAIL IOKit: dlopen/dlsym of IOKit.framework failed");
    return -1;
  }
  unsigned service = 0, polls = 0;
  for (; polls <= waitSeconds * 2 && !service; polls++) {
    service = io.getService(0, io.matching(NativePowerVRServiceName));   // kIOMainPortDefault is 0
    if (!service) usleep(500000);
  }
  if (!service) {
    probe_fail();
    probe_line("FAIL IOServiceGetMatchingService(%s): not published within %u s", NativePowerVRServiceName, waitSeconds);
    return -1;
  }
  probe_pass();
  probe_line("PASS IOServiceGetMatchingService(%s) after %u.%u s", NativePowerVRServiceName, (polls - 1) / 2, (polls - 1) % 2 * 5);
  const int kr = io.open(service, mach_task_self(), 0, &gConn);
  io.release(service);
  if (!expect("IOServiceOpen type 0", kr, kIOReturnSuccess, NULL)) return -1;

  struct NativePowerVRAbiParams params = {0};
  size_t paramsSize = sizeof params;
  const int pk = io.call(gConn, NativePowerVRMethodGetParams, NULL, 0, &params, &paramsSize);
  char detail[96];
  snprintf(detail, sizeof detail, "abi_version %u (expected %u), max_jobs %u", params.abi_version, NativePowerVRAbiVersion, params.max_jobs);
  if (!expect("GetParams", pk, kIOReturnSuccess, detail) || params.abi_version != NativePowerVRAbiVersion) {
    if (pk == kIOReturnSuccess) { probe_fail(); probe_line("FAIL GetParams: ABI version differs; stopping the IOKit stage"); }
    io.close(gConn);
    return -1;
  }

  devQueries();
  const uint32_t bo = bufferObjects();
  const uint32_t vm = vmContext(bo);
  uint32_t transferCtx = 0, computeCtx = 0;
  if (vm) {
    transferCtx = createContext(vm, DRM_PVR_CTX_TYPE_TRANSFER_FRAG, NULL, 0, "CreateContext TRANSFER_FRAG");
    // Mesa pvr_drm_compute_ctx_static_state_init(): u64 header (= the stream length, read by pvr_stream_process() as
    // u32 length + u32 zero padding), then cdm_ctx_store_pds0, _pds1, terminate_pds, terminate_pds1, resume_pds0,
    // store_pds0_b, resume_pds0_b, all zero here (see the file comment).
    uint64_t computeState[8] = {sizeof computeState, 0, 0, 0, 0, 0, 0, 0};
    computeCtx = createContext(vm, DRM_PVR_CTX_TYPE_COMPUTE, computeState, sizeof computeState, "CreateContext COMPUTE");
    // No refusal test here: Linux pvr_context_create() refuses a transfer context with static state only after it has
    // created the queues (init_fw_objs() runs late), so the refusal exercises the port's unwind of half-built firmware
    // contexts, which is not what this probe is for.
  }
  if (transferCtx) submitWithoutWork(transferCtx);

  if (computeCtx) destroyContext(computeCtx, "DestroyContext COMPUTE");
  if (transferCtx) destroyContext(transferCtx, "DestroyContext TRANSFER_FRAG");
  if (vm) {
    struct drm_pvr_ioctl_destroy_vm_context_args args = {.handle = vm};
    expect("DestroyVmContext", callIn(NativePowerVRMethodDestroyVmContext, &args, sizeof args), kIOReturnSuccess, NULL);
  }
  if (bo) expect("GemClose", closeBo(bo), kIOReturnSuccess, NULL);
  expect("IOServiceClose", io.close(gConn), kIOReturnSuccess, NULL);
  gConn = 0;
  return 0;
}

#if !POWERVRPROBED_VULKAN
int probe_vulkan(const char *library)
{
  (void)library;
  probe_line("vulkan stage not built in (build-a04br3-powervr-probe.py --vulkan)");
  return 0;
}
#endif

static void usage(void)
{
  probe_line("usage: powervrprobed [--wait SECONDS] [--no-iokit] [--no-vulkan] [--vulkan LIBRARY]");
}

int main(int argc, char **argv)
{
  gConsole = open("/dev/console", O_WRONLY | O_NOCTTY | O_CLOEXEC);
  const int consoleError = errno;
  const char *dumpFlag = getenv("PVR_DARWIN_SIPF1_DUMP");
  if (dumpFlag && strcmp(dumpFlag, "1") == 0) {
    if (gConsole < 0) {
      probe_line("FAIL SIPF1 dump: /dev/console unavailable: %s; aborting before tests", strerror(consoleError));
      return 1;
    }
    if (dup2(gConsole, STDERR_FILENO) < 0) {
      probe_line("FAIL SIPF1 dump: stderr redirect failed: %s; aborting before tests", strerror(errno));
      return 1;
    }
  }
  unsigned waitSeconds = 180;
  int iokit = 1, vulkan = POWERVRPROBED_VULKAN;
  const char *library = POWERVRPROBED_VULKAN_LIBRARY;
  for (int i = 1; i < argc; i++) {
    if (!strcmp(argv[i], "--wait") && i + 1 < argc) waitSeconds = (unsigned)strtoul(argv[++i], NULL, 10);
    else if (!strcmp(argv[i], "--no-iokit")) iokit = 0;
    else if (!strcmp(argv[i], "--no-vulkan")) vulkan = 0;
    else if (!strcmp(argv[i], "--vulkan") && i + 1 < argc) { library = argv[++i]; vulkan = 1; }
    else { usage(); return 64; }
  }
  probe_line("start: pid %d uid %d, console fd %d, vulkan %s", getpid(), getuid(), gConsole,
             !POWERVRPROBED_VULKAN ? "not built" : vulkan ? library : "skipped");
  int status = 0;
  if (iokit && ioStage(waitSeconds)) status = 1;
  if (vulkan && probe_vulkan(library)) status |= 2;
  probe_line("done: %u passed, %u failed, status %d", gPass, gFail, gFail ? (status | 4) : status);
  return gFail ? (status | 4) : status;
}

