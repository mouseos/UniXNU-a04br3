// powervrprobed: the user-space test of the NativePowerVR user client (package/powervr/NativePowerVRGpu.cpp, ABI
// package/powervr/NativePowerVRABI.h). IOKit only, no Mesa: every argument record is the unchanged Linux uAPI struct of
// linux/uapi/drm/pvr_drm.h, filled the way Mesa's winsys (src/imagination/vulkan/winsys/powervr/pvr_drm*.c, Mesa 0d94b3f397fb)
// fills it for the same ioctl.
//
// Order of the test, one UART line per step ("powervrprobed: ..."):
//   1. IOServiceGetMatchingService("NativePowerVRGpu") (polled: the service is published after the firmware boots),
//      IOServiceOpen type 0, GetParams.
//   2. DevQuery, all six types of enum drm_pvr_dev_query: first with a NULL pointer (the size the kernel expects), then
//      with the record; the counted arrays (quirks, enhancements, heaps, static data areas) the way Mesa reads them
//      (pvr_drm.c: count first, then the array).
//   3. CreateBo with DRM_PVR_BO_ALLOW_CPU_USERSPACE_ACCESS, GetBoMmapOffset, IOConnectMapMemory64 with kIOMapAnywhere (the
//      options of Mesa's darwin winsys), a written pattern read back, unmapped, mapped again and read back (same pages);
//      a BO without CPU access must be refused for mapping (pvr_gem_mmap(): -EINVAL).
//   4. CreateVmContext, VmMap of that BO into the general heap returned by the heap query, VmUnmap, a second VmUnmap that
//      must fail (drm_gpuva_find() finds nothing: -ENOENT).
//   5. CreateContext: DRM_PVR_CTX_TYPE_TRANSFER_FRAG, which takes no static state (Linux pvr_context.c
//      init_transfer_fw_objs() refuses one), as Mesa's pvr_drm_winsys_transfer_ctx_create() creates it; then
//      DRM_PVR_CTX_TYPE_COMPUTE, whose static state stream is required (init_compute_fw_objs()): the 64-byte stream of
//      Mesa's pvr_drm_compute_ctx_static_state_init() (header = stream length, then the seven CDM context-switch
//      registers in the order of pvr_stream_defs.c rogue_fwif_static_compute_context_state_stream). Mesa fills the
//      registers with its CDM store/resume PDS programs, which only Mesa's PDS generator makes; here they are zero, so the
//      context is valid for the stream parser and the firmware but must not be context-switched (no compute job is
//      submitted on it). A refusal is reported with its status.
//   6. SubmitJobs without GPU work: Mesa has no GPU null job (pvr_drm_job_null.c only moves syncobjs on the CPU) and every
//      transfer, compute or render command stream it submits points at PDS/USC programs generated by Mesa. A command stream
//      made up here would be a guess, so this stage only submits a TRANSFER_FRAG job whose stream header is malformed
//      (padding word nonzero, refused by pvr_stream_process() with -EINVAL before anything is queued), and waits on a
//      fence the connection never issued (native_powervr_fence_wait(): -EINVAL). A job that runs on the GPU is the
//      Vulkan stage's clear (powervrprobed_vulkan.c), whose streams come from Mesa.
//   7. Teardown in the reverse order, IOServiceClose; then the Vulkan stage when built in; a summary line.
//
// Output. Nothing else of this probe reaches the UART: the NativePowerVR user client has no report method (the Adreno probe
// daemon reports through NativeAdreno's SetMetadata and refused IOServiceOpen markers, which NativePowerVRGpu does not
// have). With the boot argument serial=1 (board.toml) the kernel console is UART0, and launchd's own console lines
// ("com.apple.xpc.launchd|... <Notice>: ...") appear in the a04br3 UART logs, so the probe writes /dev/console, one line
// per write() so a line does not interleave with a kernel line in the middle.
//
// Start. The a04br3 board launch hook (package/A04BR3ProbeLaunch.c, boot argument a04br3-powervrprobed=1) posix_spawns
// /private/var/ngpu/bin/powervrprobed once before launchd, as UniXNU-droidvm starts its owner service manager; the launchd
// plist that scripts/build-a04br3-powervr-probe.py also writes is only used when launchd honours it (see that script).
//
// The iPhoneOS SDK has no IOKit headers, so IOKit is opened with dlopen() and its functions declared here, as UniXNU's
// NativeAdrenoProbeDaemon.cpp does. The kern_return values are those of XNU iokit/IOKit/IOReturn.h (xnu-10063.141.1).
